def write_three_minimal(rows, out_name):
    """Three-class table, no sample-size columns (per v12 spec)."""
    keep = [r for r in rows if survives_three(r)]
    out = os.path.join(ROOT, "out", out_name)
    with open(out, "w") as fh:
        fh.write("% generated by code/render_tables_v9.py\n")
        fh.write("\\begin{tabular}{l r r r r r}\n\\hline\n")
        fh.write(
            "Dataset & $\\mu_{\\rm dj}$ & $\\mu_{\\rm open}$ & "
            "$\\mu_{\\rm closed}$ & $d_{\\rm closed{-}dj}$ & "
            "$d_{\\rm closed{-}open}$ \\\\\n\\hline\n"
        )
        for r in keep:
            fh.write(
                f"\\texttt{{{r['dataset']}}} & "
                f"{fmt_f(r['mean_dj'])} & {fmt_f(r['mean_open'])} & "
                f"{fmt_f(r['mean_tri'])} & "
                f"{fmt_f(r['d_dj_tri'], prec=2)} & "
                f"{fmt_f(r['d_open_tri'], prec=2)} \\\\\n"
            )
        fh.write("\\hline\n\\end{tabular}\n")
    print(f"Wrote {out}")


def write_size2_merged(rows, out_name):
    """Merged size-2 table: dj-vs-int columns plus three-class columns.
    Three-class cells are dashed for datasets that fail survives_three."""
    keep = [r for r in rows if survives_djns(r)]
    out = os.path.join(ROOT, "out", out_name)
    with open(out, "w") as fh:
        fh.write("% generated by code/render_tables_v9.py\n")
        fh.write("\\begin{tabular}{l r r r r r r r r r}\n\\hline\n")
        fh.write(
            "Dataset & $\\Delta$ & $E_{\\rm freq}$ & "
            "$\\mu_{\\rm dj}$ & $\\mu_{\\rm int}$ & $d$ & "
            "$\\mu_{\\rm open}$ & $\\mu_{\\rm closed}$ & "
            "$d_{\\rm open{-}dj}$ & $d_{\\rm closed{-}dj}$ "
            "\\\\\n\\hline\n"
        )
        for r in keep:
            three_ok = survives_three(r)
            o_mu = fmt_f(r['mean_open']) if three_ok else "--"
            c_mu = fmt_f(r['mean_tri']) if three_ok else "--"
            d_op = fmt_f(r['d_dj_open'], prec=2) if three_ok else "--"
            d_cl = fmt_f(r['d_dj_tri'], prec=2) if three_ok else "--"
            fh.write(
                f"\\texttt{{{r['dataset']}}} & {r['delta']} & "
                f"{fmt_int(r.get('E_freq', '0'))} & "
                f"{fmt_f(r['mean_dj'])} & {fmt_f(r['mean_ns'])} & "
                f"{fmt_f(r['d_dj_ns'], prec=2)} & "
                f"{o_mu} & {c_mu} & {d_op} & {d_cl} \\\\\n"
            )
        fh.write("\\hline\n\\end{tabular}\n")
    print(f"Wrote {out}")


